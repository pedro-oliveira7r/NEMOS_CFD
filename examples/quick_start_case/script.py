import nemos1_02 as nemos
a = nemos.Salome_Env()
b = nemos.Room(salome_env=a,dx=3.000,dy=3.000,dz=3.000,name='Room')
c = nemos.Person_seated(salome_env=a,x=2.025,thickness=0.15)
d = nemos.Person_seated(salome_env=a,x=0.975,thickness=0.15,theta=180)
e = nemos.Dip(salome_env=a,x=2.025,y=0.6)
f = nemos.Dip(salome_env=a,x=0.975,y=1)
g = nemos.Table(salome_env=a,x=1.5,dz=1)
b.insert_ceiling_opening(x=0.5, z=2.5, d=0.1)
b.insert_ceiling_opening(x=2.5, z=0.5, d=0.1)
b.insert_ceiling_opening(x=0.5, z=0.5, d=0.1)
b.insert_ceiling_opening(x=2.5, z=2.5, d=0.1)
b.add([c,d,e,f,g])
b.create_faces_groups()
b.add_box(person = c,H_Vol=1.5)
b.add_box(person = d,H_Vol=1.1)
b.add_cilinder(salome_env=a, dip = e)
b.add_cilinder(salome_env=a, dip = f)
nemos.salome_update()
b.create_mesh()

